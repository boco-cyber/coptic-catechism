#!/usr/bin/env python3
"""Verify the Arabic JSON dataset is source-controlled by syncArabicSource.py.

The Arabic dataset is not reformatted here; syncArabicSource.py owns its
content and whitespace. English is generated by syncEnglishSource.py.

Usage:
    python3 backend/src/seeds/formatDatasets.py --check
    python3 backend/src/seeds/formatDatasets.py
"""

from __future__ import annotations

import argparse
import json
from collections import Counter
from pathlib import Path

HERE = Path(__file__).resolve().parent
DATA_DIR = HERE.parents[1] / "data"

ARABIC = DATA_DIR / "catechism_qa_ar.json"
ARABIC_STRUCTURE = DATA_DIR / "arabic_structure.json"

EXPECTED_COUNT = 1424
REQUIRED_FIELDS = (
    "questionNumber",
    "bookNumber",
    "chapterNumber",
    "sourceQuestionId",
    "sourceSectionId",
    "question",
    "answer",
)


def load(path: Path) -> list[dict]:
    with path.open(encoding="utf-8") as source:
        return json.load(source)


def validate_arabic_rows(rows: list[dict], expected_count: int = EXPECTED_COUNT) -> list[str]:
    errors: list[str] = []

    if len(rows) != expected_count:
        errors.append(f"expected {expected_count} records, found {len(rows)}")

    numbers = [row.get("questionNumber") for row in rows]
    if not all(isinstance(number, int) and not isinstance(number, bool) for number in numbers):
        errors.append("questionNumber values must be integers")
    else:
        if sorted(numbers) != list(range(1, expected_count + 1)):
            errors.append(
                f"question numbers are not contiguous from 1 to {expected_count}"
            )
        duplicate_numbers = sorted(
            number for number, count in Counter(numbers).items() if count > 1
        )
        if duplicate_numbers:
            errors.append(f"duplicate questionNumber values: {duplicate_numbers[:10]}")

    source_ids = [row.get("sourceQuestionId") for row in rows]
    try:
        duplicate_source_ids = sorted(
            str(source_id)
            for source_id, count in Counter(source_ids).items()
            if count > 1
        )
    except TypeError:
        errors.append("sourceQuestionId values must be hashable scalars")
    else:
        if duplicate_source_ids:
            errors.append(
                f"duplicate sourceQuestionId values: {duplicate_source_ids[:10]}"
            )

    for index, row in enumerate(rows, start=1):
        for field in REQUIRED_FIELDS:
            if field not in row or row[field] is None:
                errors.append(f"record {index} is missing required field {field}")

        question = row.get("question")
        if not isinstance(question, str) or not question.strip():
            errors.append(f"record {index} has an empty question")

        answer = row.get("answer")
        if not isinstance(answer, str) or not answer.strip():
            errors.append(f"record {index} has an empty answer")

    return errors


def _source_section_ids() -> dict[tuple, object]:
    structure = json.loads(ARABIC_STRUCTURE.read_text(encoding="utf-8"))
    return {
        (book.get("bookNumber"), section.get("chapterNumber")): section.get(
            "sourceSectionId"
        )
        for book in structure.get("books", [])
        for section in book.get("sections", [])
    }


def _hydrate_source_section_ids(rows: list[dict]) -> list[dict]:
    if not rows or any("sourceSectionId" in row for row in rows):
        return rows

    mapping = _source_section_ids()
    return [
        {
            **row,
            "sourceSectionId": mapping.get(
                (row.get("bookNumber"), row.get("chapterNumber"))
            ),
        }
        for row in rows
    ]


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify the Arabic dataset is source-controlled",
    )
    args = parser.parse_args()

    rows = _hydrate_source_section_ids(load(ARABIC))
    errors = validate_arabic_rows(rows)
    if errors:
        details = "\n".join(f"- {error}" for error in errors)
        raise SystemExit(
            "Arabic dataset is invalid:\n"
            f"{details}\n"
            "Run syncArabicSource.py or restore the source-controlled dataset "
            "from Git"
        )

    print(
        "Arabic: source-controlled by syncArabicSource.py "
        f"({len(rows)} records); no formatting applied"
    )
    if args.check:
        print("Datasets are up to date")


if __name__ == "__main__":
    main()
